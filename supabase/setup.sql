create or replace function public.record_inventory_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.stock_quantity is distinct from old.stock_quantity then
    insert into public.inventory_movements (
      product_id, quantity_change, quantity_after, reason, order_id, actor_user_id
    ) values (
      new.id,
      new.stock_quantity - old.stock_quantity,
      new.stock_quantity,
      case
        when current_setting('app.inventory_reason', true) = 'order' then 'order'
        when new.stock_quantity > old.stock_quantity then 'restock'
        else 'correction'
      end,
      case
        when current_setting('app.inventory_reason', true) = 'order'
          and current_setting('app.inventory_order_id', true) is not null
        then current_setting('app.inventory_order_id', true)::uuid
        else null
      end,
      auth.uid()
    );
  end if;
  return new;
end;
$$;

drop trigger if exists products_record_inventory_change on public.products;
create trigger products_record_inventory_change
after update of stock_quantity on public.products
for each row execute function public.record_inventory_change();

create or replace function public.record_order_status_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.status is distinct from old.status then
    insert into public.order_status_history (order_id, old_status, new_status, actor_user_id)
    values (new.id, old.status, new.status, auth.uid());
  end if;

  if new.payment_status = 'paid' and old.payment_status is distinct from 'paid' then
    new.paid_at := coalesce(new.paid_at, now());
  end if;
  if new.status = 'shipped' and old.status is distinct from 'shipped' then
    new.shipped_at := coalesce(new.shipped_at, now());
  end if;
  if new.status = 'delivered' and old.status is distinct from 'delivered' then
    new.delivered_at := coalesce(new.delivered_at, now());
  end if;
  return new;
end;
$$;

drop trigger if exists orders_record_status_change on public.orders;
create trigger orders_record_status_change
before update of status, payment_status on public.orders
for each row execute function public.record_order_status_change();

