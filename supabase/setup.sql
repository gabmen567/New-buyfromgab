create or replace function public.place_order(
  p_customer jsonb,
  p_items jsonb,
  p_shipping_address jsonb,
  p_shipping_method_id text,
  p_payment_method text default 'whatsapp',
  p_discount_code text default null,
  p_customer_note text default ''
)
returns table (
  order_id uuid,
  order_number text,
  tracking_token uuid,
  subtotal numeric,
  discount_amount numeric,
  shipping_amount numeric,
  total_amount numeric
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_customer_id uuid;
  v_order_id uuid;
  v_order_number text;
  v_tracking_token uuid;
  v_name text;
  v_email text;
  v_phone text;
  v_subtotal numeric(12,2) := 0;
  v_discount numeric(12,2) := 0;
  v_shipping numeric(12,2);
  v_total numeric(12,2);
  v_shipping_method public.shipping_methods%rowtype;
  v_discount_code public.discount_codes%rowtype;
  v_item record;
  v_product public.products%rowtype;
begin
  if jsonb_typeof(p_customer) is distinct from 'object'
     or jsonb_typeof(p_items) is distinct from 'array'
     or jsonb_array_length(p_items) < 1
     or jsonb_array_length(p_items) > 50
     or jsonb_typeof(p_shipping_address) is distinct from 'object' then
    raise exception 'Invalid checkout details.';
  end if;

  v_name := trim(coalesce(p_customer ->> 'full_name', ''));
  v_email := lower(trim(coalesce(p_customer ->> 'email', '')));
  v_phone := trim(coalesce(p_customer ->> 'phone', ''));

  if v_name is null or char_length(v_name) < 2 or char_length(v_name) > 120
     or v_email is null
     or v_email !~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
     or char_length(v_phone) < 6 or char_length(v_phone) > 40
     or length(trim(p_shipping_address::text)) < 3 then
    raise exception 'Enter a valid name, email, phone number, and shipping address.';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_items) as input_item(value)
    where jsonb_typeof(input_item.value) is distinct from 'object'
       or coalesce(input_item.value ->> 'product_id', '') !~ '^[0-9]{1,18}$'
       or case
         when coalesce(input_item.value ->> 'quantity', '') ~ '^[0-9]{1,2}$'
           then (input_item.value ->> 'quantity')::integer < 1
             or (input_item.value ->> 'quantity')::integer > 99
         else true
       end
  ) then
    raise exception 'One or more cart items have invalid product or quantity values.';
  end if;

  select * into v_shipping_method
  from public.shipping_methods sm
  where sm.id = p_shipping_method_id and sm.is_active
  for share;
  if not found then
    raise exception 'The selected shipping method is not available.';
  end if;
  v_shipping := v_shipping_method.price;

  if p_payment_method is null or not exists (
    select 1 from public.payment_methods pm
    where pm.id = p_payment_method and pm.is_enabled
  ) then
    raise exception 'The selected payment method is not available.';
  end if;

  for v_item in
    select (input_item.value ->> 'product_id')::bigint as product_id,
           sum((input_item.value ->> 'quantity')::integer)::integer as quantity
    from jsonb_array_elements(p_items) as input_item(value)
    group by (input_item.value ->> 'product_id')::bigint
    order by product_id
  loop
    select * into v_product
    from public.products p
    where p.id = v_item.product_id and p.is_active
    for update;

    if not found then
      raise exception 'A product in the cart is no longer available.';
    end if;
    if v_product.stock_quantity < v_item.quantity then
      raise exception 'Insufficient inventory for "%".', v_product.name;
    end if;

    v_subtotal := v_subtotal + (v_product.price * v_item.quantity);
  end loop;

  if p_discount_code is not null and trim(p_discount_code) <> '' then
    select * into v_discount_code
    from public.discount_codes dc
    where dc.code = upper(trim(p_discount_code))
      and dc.is_active
      and (dc.starts_at is null or dc.starts_at <= now())
      and (dc.expires_at is null or dc.expires_at > now())
      and (dc.max_redemptions is null or dc.redemption_count < dc.max_redemptions)
    for update;

    if not found then
      raise exception 'The discount code is invalid or expired.';
    end if;
    if v_subtotal < v_discount_code.minimum_subtotal then
      raise exception 'The order does not meet the minimum subtotal for this discount.';
    end if;

    if v_discount_code.discount_type = 'percentage' then
      v_discount := round(v_subtotal * v_discount_code.discount_value / 100, 2);
    else
      v_discount := v_discount_code.discount_value;
    end if;
    v_discount := least(v_discount, v_subtotal);
  end if;

  v_total := v_subtotal - v_discount + v_shipping;

  insert into public.customers (user_id, full_name, email, phone)
  values ((select auth.uid()), v_name, v_email, v_phone)
  on conflict (user_id) do update
    set full_name = excluded.full_name,
        email = excluded.email,
        phone = excluded.phone
  returning id into v_customer_id;

  insert into public.orders (
    customer_id, shipping_method_id, discount_code_id,
    customer_name, customer_email, customer_phone, shipping_address, customer_note,
    status, payment_method, payment_status,
    subtotal, discount_amount, shipping_amount, total_amount
  ) values (
    v_customer_id, v_shipping_method.id, v_discount_code.id,
    v_name, v_email, v_phone, p_shipping_address,
    left(coalesce(p_customer_note, ''), 1000),
    'pending', p_payment_method, 'pending',
    v_subtotal, v_discount, v_shipping, v_total
  )
  returning id, orders.order_number, orders.tracking_token
  into v_order_id, v_order_number, v_tracking_token;

  for v_item in
    select (input_item.value ->> 'product_id')::bigint as product_id,
           sum((input_item.value ->> 'quantity')::integer)::integer as quantity
    from jsonb_array_elements(p_items) as input_item(value)
    group by (input_item.value ->> 'product_id')::bigint
    order by product_id
  loop
    select * into v_product from public.products p where p.id = v_item.product_id for update;

    insert into public.order_items (order_id, product_id, product_name, product_sku, quantity, unit_price)
    values (v_order_id, v_product.id, v_product.name, v_product.sku, v_item.quantity, v_product.price);

    perform set_config('app.inventory_reason', 'order', true);
    perform set_config('app.inventory_order_id', v_order_id::text, true);
    update public.products
    set stock_quantity = stock_quantity - v_item.quantity,
        sales_count = sales_count + v_item.quantity
    where id = v_product.id;
  end loop;
  perform set_config('app.inventory_reason', '', true);
  perform set_config('app.inventory_order_id', '', true);

  if v_discount_code.id is not null then
    update public.discount_codes
    set redemption_count = redemption_count + 1
    where id = v_discount_code.id;
  end if;

  return query select v_order_id, v_order_number, v_tracking_token,
                      v_subtotal, v_discount, v_shipping, v_total;
end;
$$;

create or replace function public.track_order(
  p_order_number text,
  p_tracking_token uuid
)
returns table (
  order_number text,
  status text,
  payment_status text,
  created_at timestamptz,
  shipped_at timestamptz,
  delivered_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select o.order_number, o.status, o.payment_status, o.created_at, o.shipped_at, o.delivered_at
  from public.orders o
  where o.order_number = p_order_number
    and o.tracking_token = p_tracking_token;
$$;

