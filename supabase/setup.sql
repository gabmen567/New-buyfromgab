create or replace view public.admin_dashboard_metrics
with (security_invoker = true)
as
select
  coalesce(o.valid_order_count, 0) as valid_order_count,
  coalesce(o.gross_revenue, 0)::numeric(12,2) as gross_revenue,
  coalesce(i.units_ordered, 0)::bigint as units_ordered,
  coalesce(o.customer_count, 0) as customer_count,
  coalesce(o.open_order_count, 0) as open_order_count
from (
  select
    count(*) filter (where status <> 'cancelled') as valid_order_count,
    sum(total_amount) filter (where status <> 'cancelled') as gross_revenue,
    count(distinct customer_id) filter (where status <> 'cancelled') as customer_count,
    count(*) filter (where status in ('pending', 'processing')) as open_order_count
  from public.orders
) o
cross join (
  select coalesce(sum(oi.quantity), 0)::bigint as units_ordered
  from public.order_items oi
  join public.orders o on o.id = oi.order_id
  where o.status <> 'cancelled'
) i;

create or replace view public.admin_sales_by_category
with (security_invoker = true)
as
select
  c.id as category_id,
  c.name as category_name,
  count(distinct oi.order_id) filter (where o.status <> 'cancelled') as order_count,
  coalesce(sum(oi.quantity) filter (where o.status <> 'cancelled'), 0)::bigint as units_sold,
  coalesce(sum(oi.line_total) filter (where o.status <> 'cancelled'), 0)::numeric(12,2) as sales_total
from public.categories c
left join public.products p on p.category_id = c.id
left join public.order_items oi on oi.product_id = p.id
left join public.orders o on o.id = oi.order_id
group by c.id, c.name, c.display_order;

create or replace view public.admin_top_products
with (security_invoker = true)
as
select
  p.id as product_id,
  p.name as product_name,
  p.category_id,
  coalesce(sum(oi.quantity) filter (where o.status <> 'cancelled'), 0)::bigint as units_sold,
  coalesce(sum(oi.line_total) filter (where o.status <> 'cancelled'), 0)::numeric(12,2) as sales_total
from public.products p
left join public.order_items oi on oi.product_id = p.id
left join public.orders o on o.id = oi.order_id
group by p.id, p.name, p.category_id;

